// Helper function to get course by ID
export const getCourseById = (id) => courses.find((course) => course.id === parseInt(id));

// Helper function to get instructor by ID
export const getInstructorById = (id) => instructors.find((inst) => inst.id === parseInt(id));

// Helper function to get courses by instructor ID
export const getCoursesByInstructor = (instructorId) =>
  courses.filter((course) => course.instructor_id === parseInt(instructorId));

// Helper function to get similar courses by category
export const getSimilarCourses = (courseId, limit = 3) => {
  const course = getCourseById(courseId);
  if (!course) return [];
  return courses
    .filter((c) => c.category === course.category && c.id !== parseInt(courseId))
    .slice(0, limit);
};
